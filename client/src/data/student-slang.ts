import { Language } from "@/types";

export type SlangCategory =
  | "university"
  | "life"
  | "slang"
  | "grades"
  | "processes";

export type SlangPopularity = "hot" | "popular" | "basic";

export type LocalizedText = Record<Language, string>;

export interface SlangTerm {
  term: string;
  pronunciation?: Record<string, string>;
  meaning: LocalizedText;
  example: LocalizedText;
  category: SlangCategory;
  popularity: SlangPopularity;
}

const L = (
  ru: string,
  en: string,
  fr: string,
  ar: string,
  zh: string,
): LocalizedText => ({
  [Language.RU]: ru,
  [Language.EN]: en,
  [Language.FR]: fr,
  [Language.AR]: ar,
  [Language.ZH]: zh,
});

export function pickLocalized(
  text: LocalizedText,
  language: Language,
): string {
  return text[language] || text[Language.RU];
}

